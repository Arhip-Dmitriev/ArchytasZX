"""Simon's algorithm over Z_d^(n+1) with hidden subgroup generated by (1, ..., 1): f(x)_i = x_i -
x_(i+1) into n fresh qudits, discarded; the register after F is uniform on the annihilator
{y : sum y = 0}, the X spider's support, dephased."""

from benchmarks.subjects._common import *


def _unrolled(n, d):
    """F on x, the difference oracle into y, F on x, y discarded, x measured."""
    x = unrolled("x", n + 1)
    y = unrolled("y", n)
    gates = [g for q in x for g in (Init(q), F(q))] + [Init(q) for q in y]
    for i in range(n):
        gates += [CX(x[i], y[i]), CX(x[i + 1], y[i], -1)]
    gates += [F(q) for q in x] + [Discard(q) for q in y] + [Measure(q) for q in x]
    return circuit([*x, *y], gates)


def _circuit(n, d):
    """F on the carry c (x_0), then per copy F on r (x_(i+1)) and the difference c - r into a
    fresh y, c carried on to r; F on every x, y discarded, x measured after the chain."""
    body = (Init("r"), F("r"), Init("y"), CX("c", "y"), CX("r", "y", -1))
    gates = [Init("c"), F("c"), Chain(n, body, carries=(("c", "r"),))]
    gates += [F("r"), F("c"), Discard("y"), Measure("r"), Measure("c")]
    return circuit(["r", "y", "c"], gates, registers={"r": n, "y": n})


def _spec(c):
    """X(0 -> n + 1), every leg dephased: one leg outside a box of n."""
    D = c.D
    return "\n".join(
        [
            f"x = X(0 -> 2, {D})",
            f"m = Z(1 -> 2, {D})",
            f"g = G(1 -> 0, {D})",
            f"a = Z(1 -> 2, {D})",
            f"b = G(1 -> 0, {D})",
            "wire x.out0 -- m.in0, m.out1 -- g.in0, x.out1 -- a.in0, a.out1 -- b.in0",
            f"repeat {c.N}: a, b",
            "outputs a.out0, m.out0",
            f"scalar {c.d}^(-1/2)",
        ]
    )


SUBJECT = Subject(
    id="simon",
    name="Simon's algorithm",
    category="algorithm",
    source="simon1997power",
    size_parameter="register qudits after the first",
    dimension="general",
    domain=Domain(n_min=0, d_min=1),
    equations=(Equation("main", _circuit, _spec, form="boxed"),),
)

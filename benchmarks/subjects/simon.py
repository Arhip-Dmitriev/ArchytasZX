"""Simon's algorithm over Z_d^n with hidden subgroup generated by (1, ..., 1): f(x)_i = x_i -
x_(i+1) into n - 1 fresh qudits, discarded; the register after F is uniform on the
annihilator {y : sum y = 0}, the X spider's support, dephased."""

from benchmarks.subjects._common import *


def _circuit(n, d):
    """F on x, the difference oracle into y, F on x, y discarded, x measured."""
    x = unrolled("x", n)
    y = unrolled("y", n - 1)
    gates = [g for q in x for g in (Init(q), F(q))] + [Init(q) for q in y]
    for i in range(n - 1):
        gates += [CX(x[i], y[i]), CX(x[i + 1], y[i], -1)]
    gates += [F(q) for q in x] + [Discard(q) for q in y] + [Measure(q) for q in x]
    return circuit([*x, *y], gates)


def _spec(c):
    """X(0 -> n), every leg dephased."""
    n = c.nv
    lines = [f"x = X(0 -> {n}, {c.D})"]
    for i in range(n):
        lines += [
            f"m{i} = Z(1 -> 2, {c.D})",
            f"g{i} = G(1 -> 0, {c.D})",
            f"wire x.out{i} -- m{i}.in0, m{i}.out1 -- g{i}.in0",
        ]
    lines.append("outputs " + ", ".join(f"m{i}.out0" for i in range(n)))
    lines.append(f"scalar {c.d}^(-1/2)")
    return "\n".join(lines)


SUBJECT = Subject(
    id="simon",
    name="Simon's algorithm",
    category="algorithm",
    source="simon1997power",
    size_parameter="register qudits",
    dimension="general",
    domain=Domain(n_min=1, d_min=1),
    equations=(Equation("main", _circuit, _spec, form="unrolled"),),
)
